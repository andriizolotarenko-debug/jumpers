local load = require("spec.load")
local Tiers = load("Tiers")

describe("Tiers", function()
  it("assembles the ribbon over x1-x20", function()
    local l = Tiers.look(3)
    assert.near(0.6, l.core, 1e-9); assert.equal(0, l.mid); assert.equal(0, l.sides)
    l = Tiers.look(8)
    assert.equal(1, l.core); assert.near(0.6, l.mid, 1e-9); assert.is_false(l.trimMid)
    l = Tiers.look(10)
    assert.equal(1, l.mid); assert.is_true(l.trimMid); assert.equal(0, l.sides)
    l = Tiers.look(15)
    assert.near(0.5, l.sides, 1e-9); assert.is_false(l.trimSide)
    assert.is_true(Tiers.look(20).trimSide)
  end)

  it("switches lettering at x7", function()
    assert.is_false(Tiers.look(6).extruded)
    assert.is_true(Tiers.look(7).extruded)
  end)

  it("picks tiers and effects", function()
    assert.equal(1, Tiers.index(24)); assert.equal(2, Tiers.index(25))
    assert.equal(3, Tiers.index(50)); assert.equal(4, Tiers.index(199)); assert.equal(5, Tiers.index(299))
    assert.equal(6, Tiers.index(300)); assert.equal(7, Tiers.index(1000))
    assert.is_true(Tiers.look(1000).rainbow); assert.is_false(Tiers.look(999).rainbow)
    assert.equal(4, Tiers.effects(5000))
    assert.equal(0, Tiers.effects(24)); assert.equal(4, Tiers.effects(200))
  end)

  it("grows 0.1% per jump up to +300%", function()
    assert.near(1.1, Tiers.growth(100), 1e-9)
    assert.near(2.0, Tiers.growth(1000), 1e-9)
    assert.near(4.0, Tiers.growth(3000), 1e-9)
    assert.near(4.0, Tiers.growth(9000), 1e-9)
  end)

  it("names events", function()
    assert.equal("stage", Tiers.event(5)); assert.equal("stage", Tiers.event(10)); assert.equal("stage", Tiers.event(20))
    assert.equal("tier", Tiers.event(25)); assert.equal("tier", Tiers.event(200))
    assert.is_nil(Tiers.event(26))
    assert.equal("ornament", Tiers.event(75)); assert.equal("ornament", Tiers.event(150))
    assert.equal("tier", Tiers.event(300)); assert.equal("tier", Tiers.event(1000))
    for _, n in ipairs({ 350, 400, 500, 750 }) do assert.equal("ornament", Tiers.event(n)) end
    assert.equal("pulse", Tiers.event(30)); assert.equal("pulse", Tiers.event(60)); assert.equal("pulse", Tiers.event(1010))
  end)

  it("adds ornaments at x75, x150, x350, x400, x500, x750", function()
    assert.equal(0, Tiers.look(74).ornaments); assert.equal(1, Tiers.look(75).ornaments)
    assert.equal(2, Tiers.look(349).ornaments); assert.equal(3, Tiers.look(350).ornaments)
    assert.equal(6, Tiers.look(9999).ornaments)
  end)

  it("cycles hues", function()
    local r = Tiers.hsv(0, 1, 1); assert.same({ 1, 0, 0 }, r)
    local g = Tiers.hsv(1 / 3, 1, 1); assert.near(1, g[2], 1e-9); assert.near(0, g[1], 1e-9)
  end)

  it("tints the face 20% toward the glow", function()
    local f = Tiers.look(30).face
    assert.near(1 - 0.2 * (1 - 0x1e / 255), f[1], 1e-9)
    assert.near(1, f[2], 1e-9)
  end)
end)
